def seed_countries():

    print("Starting country seeding...")

    inserted = 0
    skipped = 0

    for country in COUNTRIES:

        existing = Country.query.filter_by(
            short_name=country["short_name"]
        ).first()

        if existing:
            print(
                f"SKIPPED: {country['name']} "
                f"({country['short_name']}) already exists"
            )
            skipped += 1
            continue

        new_country = Country(
            id=uuid.uuid4(),
            name=country["name"],
            short_name=country["short_name"],
            currency=country["currency"],
            currency_short=country["currency_short"],
            flag_image_url=country["flag_image_url"],
            cordinates=country["cordinates"],
            continent=country["continent"],
        )

        db.session.add(new_country)

        print(
            f"INSERTING: {country['continent']} -> "
            f"{country['name']}"
        )

        inserted += 1

    try:
        db.session.commit()

        print("\n========================================")
        print("COUNTRY SEEDING COMPLETED")
        print("========================================")
        print(f"Inserted : {inserted}")
        print(f"Skipped  : {skipped}")
        print(f"Total    : {inserted + skipped}")
        print("========================================")

    except Exception as e:

        db.session.rollback()

        print("\nERROR INSERTING COUNTRIES")
        print(str(e))


if __name__ == "__main__":

    with app.app_context():
        seed_countries()